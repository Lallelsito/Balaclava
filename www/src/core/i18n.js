  function interpolate(str, vars) {
    if (!vars || typeof str !== 'string') return str;
    return str.replace(/\{([a-zA-Z0-9_]+)\}/g, (_, k) => (vars[k] !== undefined && vars[k] !== null ? String(vars[k]) : ''));
  }

  function t(key, vars) {
    const dict = STRINGS[currentLang] || STRINGS[DEFAULT_LANG];
    let val = dict[key];
    if (val === undefined) val = STRINGS[DEFAULT_LANG][key];
    if (val === undefined) return key;
    return interpolate(val, vars);
  }

  function tp(oneKey, manyKey, n, vars) {
    const num = Number(n) || 0;
    return t(num === 1 ? oneKey : manyKey, { n: num, ...(vars || {}) });
  }

